const VIEW_GROUPS = new Set(['View', 'Help']);

export function metaFor(id: string, menuGroup: string | undefined): { group: string; when: string; mutates: boolean; risky: boolean; known: boolean } {
  const row = ROWS[id];
  const rule = PREFIX.find(([re]) => re.test(id));
  const group = menuGroup ?? rule?.[1] ?? 'Other';
  const flags = row?.[1] ?? '';
  const when = row?.[0] ?? rule?.[2] ?? '';
  const mutates = flags.includes('v') ? false : !VIEW_GROUPS.has(group);
  return { group, when, mutates, risky: flags.includes('r'), known: !!row };
}
